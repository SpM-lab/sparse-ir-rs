//! The default sampling points of bases of centrosymmetric kernels are those
//! of main before the double-double SVE by ACA: the Matsubara points exactly,
//! the tau points to 1e-10·β.
//!
//! Reference data: the default points of `FiniteTempBasis::new(kernel, β,
//! Some(ε), None)` on main at 28a30e3, printed by
//! an example that calls `default_matsubara_sampling_points_i64(false /
//! true)`, `default_matsubara_sampling_points_i64_with_mitigate(false, true,
//! L)` and `default_tau_sampling_points` (sorted), with the shortest
//! round-trip representation of the floats.
//!
//! The data were taken on aarch64 macOS, where the tau points agree bitwise
//! (in f64, ε = 1e-6, the SVE is that of main bitwise; in double-double,
//! ε = 1e-10 and 1e-12, the ACA SVE gives the same roots of u_L after
//! rounding the functions to f64). Other platforms round the f64 SVE
//! differently (on x86_64 Linux the tau points of main itself differ by
//! about 1e-13·β), hence the tolerance, far below any change of method.

use sparse_ir::basis::FiniteTempBasis;
use sparse_ir::kernel::{
    CentrosymmKernel, KernelProperties, LogisticKernel, RegularizedBoseKernel,
};
use sparse_ir::traits::{Bosonic, Fermionic, StatisticsType};

#[derive(Clone, Copy, Debug)]
enum KernelKind {
    Logistic,
    RegularizedBose,
}

struct Case {
    kernel: KernelKind,
    fermionic: bool,
    lambda: f64,
    beta: f64,
    eps: f64,
    size: usize,
    all: &'static [i64],
    positive: &'static [i64],
    mitigate: &'static [i64],
    tau: &'static [f64],
}

fn check_case<K, S>(case: &Case, kernel: K) -> Vec<String>
where
    K: KernelProperties + CentrosymmKernel + Clone + 'static,
    S: StatisticsType + 'static,
{
    let basis = FiniteTempBasis::<K, S>::new(kernel, case.beta, Some(case.eps), None).unwrap();
    let name = format!(
        "{:?} Λ={} ε={} {}",
        case.kernel,
        case.lambda,
        case.eps,
        if case.fermionic { "F" } else { "B" }
    );
    let mut failures = Vec::new();
    if basis.size() != case.size {
        failures.push(format!("{name}: size {} vs {}", basis.size(), case.size));
        return failures;
    }
    let l = basis.size();
    for (what, got, expected) in [
        (
            "all",
            basis.default_matsubara_sampling_points_i64(false).unwrap(),
            case.all,
        ),
        (
            "positive",
            basis.default_matsubara_sampling_points_i64(true).unwrap(),
            case.positive,
        ),
        (
            "mitigate",
            basis
                .default_matsubara_sampling_points_i64_with_mitigate(false, true, l)
                .unwrap(),
            case.mitigate,
        ),
    ] {
        if got != expected {
            failures.push(format!(
                "{name}: Matsubara points ({what}) {got:?} vs {expected:?}"
            ));
        }
    }
    let mut tau = basis.default_tau_sampling_points().unwrap();
    tau.sort_by(|a, b| a.partial_cmp(b).unwrap());
    let close = tau.len() == case.tau.len()
        && tau
            .iter()
            .zip(case.tau)
            .all(|(a, b)| (a - b).abs() <= 1e-10 * case.beta);
    if !close {
        failures.push(format!("{name}: tau points {tau:?} vs {:?}", case.tau));
    }
    failures
}

#[test]
fn default_points_of_centrosymmetric_kernels_are_those_of_main() {
    let mut failures = Vec::new();
    for case in CASES {
        failures.extend(match (case.kernel, case.fermionic) {
            (KernelKind::Logistic, true) => {
                check_case::<_, Fermionic>(case, LogisticKernel::new(case.lambda).unwrap())
            }
            (KernelKind::Logistic, false) => {
                check_case::<_, Bosonic>(case, LogisticKernel::new(case.lambda).unwrap())
            }
            (KernelKind::RegularizedBose, _) => {
                // Deprecated, but still supported until it is removed (#273).
                #[allow(deprecated)]
                let kernel = RegularizedBoseKernel::new(case.lambda).unwrap();
                check_case::<_, Bosonic>(case, kernel)
            }
        });
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

